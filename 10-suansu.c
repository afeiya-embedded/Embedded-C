#include <stdio.h>

/**
 * @brief 主函数，程序入口点，演示自增和自减运算符的前置和后置使用。
 *
 * 初始化几个整数变量，通过一系列操作展示前置和后置自增、自减运算符
 * 在赋值语句和表达式中的不同行为，并输出每次操作后的变量值。
 *
 * @param argc 命令行参数的数量。
 * @param argv 指向命令行参数字符串数组的指针。
 * @return int 程序返回状态码，0 表示正常结束。
 */
int main(int argc, char const *argv[])
{
    // 初始化变量 x 为 5，y 为 9，z 用于存储中间计算结果
    int x = 5, y = 9, z;

    // ---------------------- 前置自增运算符演示 ----------------------
    // 前置自增运算符：先将 x 的值加 1，再将加 1 后的 x 值赋给 z
    // 执行前 x = 5，执行后 z 的值为 6，x 的值变为 6
    z = ++x;
    // 输出当前 z 和 x 的值
    printf("z=%d,x=%d\n", z, x);

    // 重置 x 和 y 的值，以便后续演示
    x = 5, y = 9;

    // ---------------------- 后置自增运算符演示 ----------------------
    // 后置自增运算符：先将 x 的当前值赋给 z，再将 x 的值加 1
    // 执行前 x = 5，执行后 z 的值为 5，x 的值变为 6（原注释此处有误，已修正）
    z = x++;
    // 输出当前 z 和 x 的值
    printf("z=%d,x=%d\n", z, x);

    // 重置 x 和 y 的值，以便后续演示
    x = 5, y = 9;

    // ---------------------- 前置自减运算符演示 ----------------------
    // 前置自减运算符：先将 x 的值减 1，再将减 1 后的 x 值赋给 z
    // 执行前 x = 5，执行后 z 的值为 4，x 的值变为 4（原注释此处有误，已修正）
    z = --x;
    // 输出当前 z 和 x 的值
    printf("z=%d,x=%d\n", z, x);

    // 重置 x 和 y 的值，以便后续演示
    x = 5, y = 9;

    // ---------------------- 后置自减运算符演示 ----------------------
    // 后置自减运算符：先将 x 的当前值赋给 z，再将 x 的值减 1
    // 执行前 x = 5，执行后 z 的值为 5，x 的值变为 4（原注释此处有误，已修正）
    z = x--;
    // 输出当前 z 和 x 的值
    printf("z=%d,x=%d\n", z, x);

    // 重置 x 和 y 的值，以便后续演示
    x = 5, y = 9;

    // ---------------------- 表达式中前置自增和后置自增运算符演示 ----------------------
    // 先将 x 的值加 1，此时 x 变为 6，再与 y 的当前值 9 相加，结果 15 赋给 z，最后 y 的值加 1 变为 10
    // 执行后，z 的值为 15，x 的值变为 6，y 的值变为 10
    z = ++x + y++;
    // 输出当前 z、x 和 y 的值
    printf("z=%d,x=%d,y=%d\n", z, x, y);

    // 重置 x 和 y 的值，以便后续演示
    x = 5, y = 9;

    // ---------------------- 表达式中前置自减和后置自增运算符演示 ----------------------
    // 先将 x 的值减 1，此时 x 变为 4，再与 y 的当前值 9 相加，结果 13 赋给 z，最后 y 的值加 1 变为 10（原注释此处有误，已修正）
    // 执行后，z 的值为 13，x 的值变为 4，y 的值变为 10
    z = --x + y++;
    // 输出当前 z、x 和 y 的值
    printf("z=%d,x=%d,y=%d\n", z, x, y);

    // 重置 x 和 y 的值，以便后续演示
    x = 5, y = 9;

    // ---------------------- 表达式中前置自增和后置自减运算符演示 ----------------------
    // 先将 x 的值加 1，此时 x 变为 6，再与 y 的当前值 9 相加，结果 15 赋给 z，最后 y 的值减 1 变为 8（原注释此处有误，已修正）
    // 执行后，z 的值为 15，x 的值变为 6，y 的值变为 8
    z = ++x + y--;
    // 输出当前 z、x 和 y 的值
    printf("z=%d,x=%d,y=%d\n", z, x, y);

    // 程序正常结束，返回状态码 0
    return 0;
}
