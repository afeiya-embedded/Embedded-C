#include <stdio.h>

/**
 * @brief 演示 C 语言中逻辑与（&&）和逻辑或（||）运算符的使用。
 * 
 * 程序定义了两个整数变量 x 和 y，通过不同的逻辑表达式组合，
 * 展示逻辑与和逻辑或运算符的运算规则，并输出每个表达式的计算结果。
 * 
 * @param argc 命令行参数的数量。
 * @param argv 指向命令行参数字符串数组的指针。
 * @return int 程序返回状态码，0 表示正常结束。
 */
int main(int argc, char const *argv[])
{
    // 定义两个整型变量 x 和 y，并分别初始化为 5 和 18
    int x = 5, y = 18;

    // 使用逻辑与（&&）运算符，当两个操作数都为真时，结果为真（1），否则为假（0）
    // 表达式 (x >= 5) 为真，(y < 20) 为真，所以整个表达式为真
    printf("1:ret=%d\n", (x >= 5) && (y < 20));        // 结果值为1
    // 表达式 ((x + 1) >= 0) 为真，但 (y < 17) 为假，所以整个表达式为假
    printf("2:ret=%d\n", ((x + 1) >= 0) && (y < 17));  // 结果值为0
    // 表达式 ((x - 8) >= 0) 为假，(y == 18) 为真，所以整个表达式为假
    printf("3:ret=%d\n", ((x - 8) >= 0) && (y == 18)); // 结果值为0
    // 表达式 ((x - 5) > 0) 为假，(y != 18) 为假，所以整个表达式为假
    printf("4:ret=%d\n", ((x - 5) > 0) && (y != 18));  // 结果值为0

    // 使用逻辑或（||）运算符，当两个操作数至少有一个为真时，结果为真（1），否则为假（0）
    // 表达式 (x >= 5) 为真，(y < 20) 为真，所以整个表达式为真
    printf("5:ret=%d\n", ((x >= 5)) || (y < 20));      // 结果值为1
    // 表达式 ((x + 1) >= 0) 为真，(y < 17) 为假，所以整个表达式为真
    printf("6:ret=%d\n", ((x + 1) >= 0) || (y < 17));  // 结果值为1
    // 表达式 ((x - 8) >= 0) 为假，(y == 18) 为真，所以整个表达式为真
    printf("7:ret=%d\n", ((x - 8) >= 0) || (y == 18)); // 结果值为1
    // 表达式 ((x - 5) > 0) 为假，(y != 18) 为假，所以整个表达式为假
    printf("8:ret=%d\n", ((x - 5) > 0) || (y != 18));  // 结果值为0

    // 程序正常结束，返回状态码 0
    return 0;
}
