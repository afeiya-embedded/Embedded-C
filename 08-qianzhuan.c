#include <stdio.h>

/**
 * @brief 演示 C 语言中的显式和隐式类型转换。
 * 
 * 本程序定义了整数和浮点数变量，分别进行显式和隐式类型转换，
 * 并输出转换后的结果，以此展示两种类型转换的差异。
 * 
 * @param argc 命令行参数的数量。
 * @param argv 指向命令行参数字符串数组的指针。
 * @return int 程序返回状态码，0 表示正常结束。
 */
int main(int argc, char const *argv[])
{
    // 定义整数变量 a 并初始化为 2，b 初始化为 0
    int a = 2, b = 0;
    // 定义浮点数变量 c 并初始化为 4.8，d 初始化为 3.3
    float c = 4.8, d = 3.3;

    // 显式强制类型转换：先计算 a + c + d 的值，再将结果转换为 int 类型赋值给 b
    b = (int)(a + c + d); 
    // 输出显式类型转换后的 b 的值
    printf("b = %d\n", b);

    // 隐式强制类型转换：计算 a + c + d 的值，由于 b 是 int 类型，
    // 编译器会自动将计算结果转换为 int 类型赋值给 b
    b = a + c + d; 
    // 输出隐式类型转换后的 b 的值
    printf("b = %d\n", b);
    // 程序正常结束，返回状态码 0
    return 0;
}
