#include <stdio.h>

#define PI 3.1415926

/**
 * @brief 计算并输出指定半径的圆的面积和周长。
 * 
 * 程序提示用户输入圆的半径，读取用户输入后，
 * 计算并输出该圆的面积和周长。
 * 
 * @param argc 命令行参数的数量。
 * @param argv 指向命令行参数字符串数组的指针。
 * @return int 程序返回状态码，0 表示正常结束。
 */
int main(int argc, char const *argv[])
{
    // 定义一个浮点型变量 r，用于存储用户输入的圆的半径
    float r;
    // 提示用户输入圆的半径
    printf("请输入圆的半径>:");
    // 从标准输入读取一个浮点数，并将其存储到变量 r 中
    scanf("%f",&r);
    // 输出用户输入的圆的半径
    printf("圆的半径为:%f\n",r);
    // 计算并输出圆的面积，根据公式 S = π * r²
    printf("圆的面积为:%f\n",r*r*PI);
    // 计算并输出圆的周长，根据公式 C = 2 * π * r
    printf("圆的周长为:%f\n",r*2*PI);
    // 程序正常结束，返回状态码 0
    return 0;
}
