#include <stdio.h>

#define  M  3.0e-23 
/**
 * @brief 计算并输出指定夸脱数的水中包含的水分子数量。
 * 
 * 程序提示用户输入水的夸脱数，读取用户输入后，
 * 计算并输出该夸脱数对应的水分子数量。
 * 
 * @param argc 命令行参数的数量。
 * @param argv 指向命令行参数字符串数组的指针。
 * @return int 程序返回状态码，0 表示正常结束。
 */
int main(int argc, char const *argv[])
{
    // 提示用户输入水的夸脱数
    printf("请输入水的夸脱数>:");
    // 定义一个整型变量 num，用于存储用户输入的水的夸脱数
    int num;
    // 从标准输入读取一个整数，并将其存储到变量 num 中
    scanf("%d",&num);
    // 输出用户输入的水的夸脱数
    printf("水的夸脱数为:%d\n",num);

    // 计算这么多的夸脱有多少个水分子
    // 1 夸脱的水约为 950 克，M 为单个水分子的质量（单位：克）
    // 通过 num * 950 计算总质量，再除以单个水分子质量 M 得到水分子数量
    printf("%d 夸脱的水中有 %e 个水分子\n",num,num*950/M);
    // 程序正常结束，返回状态码 0
    return 0;
}
