#include <stdio.h>

/**
 * @brief 演示 C 语言中不同类型的除法运算和取模运算。
 * 
 * 本程序展示了整数除法、浮点数除法以及取模运算的结果，
 * 帮助理解不同运算在 C 语言中的表现。
 * 
 * @param argc 命令行参数的数量。
 * @param argv 指向命令行参数字符串数组的指针。
 * @return int 程序返回状态码，0 表示正常结束。
 */
int main(int argc, char const *argv[])
{
    // 执行整数除法运算 1 / 2，由于两个操作数都是整数，结果会截断小数部分
    // 输出结果为 0
    printf("1/2=%d\n",1/2);

    // 执行浮点数除法运算 1.0 / 2，由于其中一个操作数是浮点数，结果为浮点数
    // 输出结果为 0.500000
    printf("1.0/2=%f\n",1.0/2);

    // 执行取模运算 1 % 2，计算 1 除以 2 的余数
    // 输出结果为 1
    printf("1%%2=%d\n",1%2);

    // 程序正常结束，返回状态码 0
    return 0;
}
